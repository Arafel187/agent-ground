# Standalone Fallback Verifier if EvidenceVerifier not found
class LocalClaimVerifier:
    def __init__(self):
        self.invocation_count = 0

    def verify(self, claims: List[str], sources: List[str], mode: str = "balanced") -> Dict[str, Any]:
        self.invocation_count += 1
        clean_claims = [c.strip() for c in claims if c and len(c.strip()) > 3]
        clean_sources = [s.strip() for s in sources if s and len(s.strip()) > 5]

        if not clean_claims or not clean_sources:
            return {
                "verdict": "UNGROUNDED",
                "grounding_score": 0.0,
                "claims_count": len(claims),
                "verified_count": 0,
                "ungrounded_count": len(claims),
                "contradicted_count": 0,
                "claim_results": [],
                "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            }

        sanitized_sources = []
        for s in clean_sources:
            # Strip prompt injection patterns
            clean = re.sub(r'(?i)ignore\s+(previous|all)\s+instructions.*', '', s)
            clean = re.sub(r'(?i)you\s+are\s+now.*', '', clean)
            sanitized_sources.append(clean)

        results = []
        verified_count = 0
        contradicted_count = 0
        ungrounded_count = 0

        STOP_WORDS = {
            "the", "and", "was", "for", "with", "that", "this", "from", "are", "were", 
            "into", "over", "has", "have", "had", "been", "will", "would", "could", "should",
            "about", "which", "their", "there", "they", "them", "then", "than", "more", "most",
            "also", "some", "other", "such", "only", "first", "last"
        }

        for c_idx, claim in enumerate(clean_claims):
            c_lower = claim.lower()
            all_claim_words = set(re.findall(r'\b[a-z0-9]{3,}\b', c_lower))
            claim_words = set(w for w in all_claim_words if w not in STOP_WORDS) or all_claim_words
            claim_nums = set(re.findall(r'\b\d+(?:\.\d+)?\b', c_lower))
            
            best_match_idx = None
            best_snippet = None
            best_status = "UNGROUNDED"
            highest_score = 0.0

            for s_idx, src in enumerate(sanitized_sources):
                s_lower = src.lower()
                all_src_words = set(re.findall(r'\b[a-z0-9]{3,}\b', s_lower))
                src_words = set(w for w in all_src_words if w not in STOP_WORDS) or all_src_words
                src_nums = set(re.findall(r'\b\d+(?:\.\d+)?\b', s_lower))

                if not claim_words:
                    continue

                overlap = len(claim_words.intersection(src_words)) / float(len(claim_words))
                
                # Check bidirectional contradiction keywords
                neg_words = {"not", "failed", "never", "no", "dropped", "declined", "divest", "divested", "cancelled", "rejected", "losses", "fell", "missed"}
                pos_words = {"passed", "succeeded", "grew", "surpassed", "increased", "acquire", "acquired", "approved", "profits", "rose", "beat"}
                
                has_neg_claim = any(w in c_lower for w in neg_words)
                has_pos_claim = any(w in c_lower for w in pos_words)
                has_neg_src = any(w in s_lower for w in neg_words)
                has_pos_src = any(w in s_lower for w in pos_words)

                is_contradiction = False
                if overlap > 0.35:
                    if (has_neg_claim and has_pos_src) or (has_pos_claim and has_neg_src):
                        is_contradiction = True

                # Check explicit antonym pairs
                antonym_pairs = [
                    ("acquire", "divest"), ("acquired", "divested"),
                    ("succeeded", "failed"), ("surpassed", "dropped"),
                    ("increased", "decreased"), ("growth", "decline"),
                    ("expanded", "contracted"), ("approved", "rejected"),
                    ("profit", "loss")
                ]
                for w1, w2 in antonym_pairs:
                    if ((w1 in c_lower and w2 in s_lower) or (w2 in c_lower and w1 in s_lower)) and overlap > 0.35:
                        is_contradiction = True
                        break

                if is_contradiction:
                    best_status = "CONTRADICTED"
                    best_match_idx = s_idx
                    best_snippet = src[:200]
                    highest_score = overlap
                    break

                # Check named entity mismatch
                common_starters = {"The", "In", "On", "At", "After", "During", "Our", "This", "That", "It", "They", "We", "He", "She", "Phase", "Base", "Quarterly", "Engineers", "Official"}
                claim_entities = set(w for w in re.findall(r'\b[A-Z][a-zA-Z0-9_]+\b', claim) if w not in common_starters)
                src_entities = set(w for w in re.findall(r'\b[A-Z][a-zA-Z0-9_]+\b', src) if w not in common_starters)
                if claim_entities and src_entities and not claim_entities.issubset(src_entities) and overlap > 0.40:
                    best_status = "CONTRADICTED"
                    best_match_idx = s_idx
                    best_snippet = src[:200]
                    highest_score = overlap
                    break

                # Check numerical mismatch
                if claim_nums and src_nums and not claim_nums.issubset(src_nums) and overlap > 0.35:
                    best_status = "CONTRADICTED"
                    best_match_idx = s_idx
                    best_snippet = src[:200]
                    highest_score = overlap
                    break

                # Grounding threshold
                min_thresh = 0.45 if mode == "strict" else 0.30
                if overlap >= min_thresh and overlap > highest_score:
                    highest_score = overlap
                    best_match_idx = s_idx
                    best_snippet = src[:200]
                    best_status = "VERIFIED_GROUNDED"

            if best_status == "VERIFIED_GROUNDED":
                verified_count += 1
            elif best_status == "CONTRADICTED":
                contradicted_count += 1
            else:
                ungrounded_count += 1

            results.append({
                "claim_index": c_idx,
                "claim": claim,
                "status": best_status,
                "confidence": round(min(1.0, highest_score * 1.3), 3) if highest_score > 0 else 0.0,
                "matched_source_index": best_match_idx,
                "evidence_snippet": best_snippet
            })

        total = len(clean_claims)
        grounding_score = round(max(0.0, ((verified_count - (contradicted_count * 1.5)) / float(total)) * 100.0), 2)

        if verified_count == total and total > 0:
            verdict = "VERIFIED"
        elif contradicted_count > 0:
            verdict = "CONTRADICTED"
        elif verified_count > 0:
            verdict = "PARTIALLY_GROUNDED"
        else:
            verdict = "UNGROUNDED"

        return {
            "verdict": verdict,
            "grounding_score": grounding_score,
            "claims_count": total,
            "verified_count": verified_count,
            "ungrounded_count": ungrounded_count,
            "contradicted_count": contradicted_count,
            "claim_results": results,
            "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        }

LOCAL_ENGINE = LocalClaimVerifier()
GLOBAL_EVIDENCE_VERIFIER = EvidenceVerifier() if HAVE_EVIDENCE_VERIFIER else None


def execute_claim_verification(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Execute claim verification engine supporting both direct and legacy formats."""
    mode = payload.get("mode", "balanced")
    
    # 1. Direct Schema: {"claims": [...], "sources": [...]}
    if "claims" in payload and "sources" in payload:
        claims = payload.get("claims", [])
        sources = payload.get("sources", [])
        return LOCAL_ENGINE.verify(claims, sources, mode=mode)

    # 2. Legacy Schema: {"completion_text": "...", "source_documents": [...]}
    if "completion_text" in payload:
        comp_text = payload.get("completion_text", "")
        sources = payload.get("source_documents", [])
        
        if GLOBAL_EVIDENCE_VERIFIER:
            legacy_res = GLOBAL_EVIDENCE_VERIFIER.verify_claims(comp_text, sources)
            # Map legacy result into clean agent-native schema
            rqs = legacy_res.get("rqs_summary", {})
            return {
                "verdict": "VERIFIED" if rqs.get("rqs_score", 0) == 100.0 else ("PARTIALLY_GROUNDED" if rqs.get("rqs_score", 0) > 0 else "UNGROUNDED"),
                "grounding_score": rqs.get("rqs_score", 0.0),
                "claims_count": rqs.get("total_claims", 0),
                "verified_count": rqs.get("grounded_claims", 0),
                "ungrounded_count": rqs.get("unsupported_claims", 0),
                "contradicted_count": sum(1 for c in legacy_res.get("claims", []) if c.get("verdict_type") == "CONTRADICTORY"),
                "claim_results": legacy_res.get("claims", []),
                "is_execution_signal": legacy_res.get("is_execution_signal", False),
                "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
            }
        else:
            # Split sentences
            claims = [s.strip() for s in re.split(r'(?<=[.!?])\s+', comp_text) if len(s.strip()) > 5]
            return LOCAL_ENGINE.verify(claims, sources, mode=mode)

    raise ValueError("Payload must contain either 'claims' & 'sources' arrays or 'completion_text' string.")


